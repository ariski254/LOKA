using System.Text;
using Loka.Core.Enums;
using Loka.Core.Interfaces;
using Loka.Core.Models;
using Loka.Infrastructure.FileSystem;

namespace Loka.Runtime.Nginx;

public class NginxService : INginxService
{
    private readonly IConfigurationService _configService;
    private readonly IRuntimeDetector _detector;
    private readonly IProcessManager _processManager;
    private readonly ILogService _logger;

    public NginxService(
        IConfigurationService configService,
        IRuntimeDetector detector,
        IProcessManager processManager,
        ILogService logger)
    {
        _configService = configService;
        _detector = detector;
        _processManager = processManager;
        _logger = logger;
    }

    public async Task<(bool IsValid, string Output)> ValidateConfigurationAsync()
    {
        var info = await _detector.DetectNginxAsync();
        if (info == null || !info.IsInstalled || !File.Exists(info.ExecutablePath))
        {
            return (false, "Nginx executable not found.");
        }

        try
        {
            var confPath = Path.Combine(_configService.Config.Paths.EtcPath, "nginx", "nginx.conf");
            var confArg = File.Exists(confPath) ? $" -c \"{confPath}\"" : "";
            var result = await _processManager.ExecuteAsync(info.ExecutablePath, $"-p \"{info.DirectoryPath}\"{confArg} -t", workingDirectory: info.DirectoryPath);
            var output = (result.StandardOutput + " " + result.StandardError).Trim();
            bool isValid = result.Success || output.Contains("syntax is ok", StringComparison.OrdinalIgnoreCase) || output.Contains("test is successful", StringComparison.OrdinalIgnoreCase);

            if (isValid)
            {
                _logger.LogInfo("Nginx", "Configuration syntax is OK.");
            }
            else
            {
                _logger.LogError("Nginx", $"Configuration validation failed: {output}");
            }

            return (isValid, output);
        }
        catch (Exception ex)
        {
            _logger.LogError("Nginx", "Exception validating Nginx configuration", ex);
            return (false, ex.Message);
        }
    }

    public async Task<bool> GenerateServerBlockAsync(ProjectInfo project)
    {
        try
        {
            var sitesDir = Path.Combine(_configService.Config.Paths.ConfigPath, "nginx", "sites-enabled");
            if (!Directory.Exists(sitesDir))
            {
                Directory.CreateDirectory(sitesDir);
            }

            var docRoot = string.IsNullOrEmpty(project.DocumentRoot) ? project.Path : project.DocumentRoot;
            docRoot = docRoot.Replace('\\', '/').TrimEnd('/');

            var confFile = Path.Combine(sitesDir, $"{project.Domain}.conf");
            var sb = new StringBuilder();

            bool isStaticOnly = project.Framework == ProjectFramework.StaticHtml ||
                               (project.Framework == ProjectFramework.React && !File.Exists(Path.Combine(docRoot, "index.php"))) ||
                               (project.Framework == ProjectFramework.Vue && !File.Exists(Path.Combine(docRoot, "index.php"))) ||
                               (project.Framework == ProjectFramework.Vite && !File.Exists(Path.Combine(docRoot, "index.php")));

            sb.AppendLine($"# Server block for {project.Domain} generated by Loka ({project.FrameworkName})");
            sb.AppendLine("server {");
            sb.AppendLine($"    listen {_configService.Config.Services.NginxPort};");
            sb.AppendLine($"    server_name {project.Domain} www.{project.Domain};");
            sb.AppendLine($"    root \"{docRoot}\";");
            if (isStaticOnly)
            {
                sb.AppendLine("    index index.html index.htm;");
                sb.AppendLine();
                sb.AppendLine("    location / {");
                sb.AppendLine("        try_files $uri $uri/ /index.html =404;");
                sb.AppendLine("    }");
            }
            else
            {
                sb.AppendLine("    index index.php index.html index.htm;");
                sb.AppendLine();
                sb.AppendLine("    location / {");
                sb.AppendLine("        try_files $uri $uri/ /index.php?$query_string;");
                sb.AppendLine("    }");
                sb.AppendLine();
                sb.AppendLine("    location ~ \\.php$ {");
                sb.AppendLine("        fastcgi_pass   127.0.0.1:9000;");
                sb.AppendLine("        fastcgi_index  index.php;");
                sb.AppendLine("        fastcgi_param  SCRIPT_FILENAME $document_root$fastcgi_script_name;");
                sb.AppendLine("        include        fastcgi_params;");
                sb.AppendLine("    }");
            }
            sb.AppendLine("}");

            var sslCertDir = Path.Combine(_configService.Config.Paths.ConfigPath, "ssl").Replace('\\', '/');
            var certPath = Path.Combine(_configService.Config.Paths.ConfigPath, "ssl", $"{project.Domain}.crt");
            var keyPath = Path.Combine(_configService.Config.Paths.ConfigPath, "ssl", $"{project.Domain}.key");
            bool hasSsl = project.HasSsl || (File.Exists(certPath) && File.Exists(keyPath));

            if (hasSsl)
            {
                sb.AppendLine();
                sb.AppendLine("# HTTPS SSL block for " + project.Domain);
                sb.AppendLine("server {");
                sb.AppendLine("    listen 443 ssl;");
                sb.AppendLine($"    server_name {project.Domain} www.{project.Domain};");
                sb.AppendLine($"    root \"{docRoot}\";");
                if (isStaticOnly)
                {
                    sb.AppendLine("    index index.html index.htm;");
                    sb.AppendLine($"    ssl_certificate \"{sslCertDir}/{project.Domain}.crt\";");
                    sb.AppendLine($"    ssl_certificate_key \"{sslCertDir}/{project.Domain}.key\";");
                    sb.AppendLine();
                    sb.AppendLine("    location / {");
                    sb.AppendLine("        try_files $uri $uri/ /index.html =404;");
                    sb.AppendLine("    }");
                }
                else
                {
                    sb.AppendLine("    index index.php index.html index.htm;");
                    sb.AppendLine($"    ssl_certificate \"{sslCertDir}/{project.Domain}.crt\";");
                    sb.AppendLine($"    ssl_certificate_key \"{sslCertDir}/{project.Domain}.key\";");
                    sb.AppendLine();
                    sb.AppendLine("    location / {");
                    sb.AppendLine("        try_files $uri $uri/ /index.php?$query_string;");
                    sb.AppendLine("    }");
                    sb.AppendLine();
                    sb.AppendLine("    location ~ \\.php$ {");
                    sb.AppendLine("        fastcgi_pass   127.0.0.1:9000;");
                    sb.AppendLine("        fastcgi_index  index.php;");
                    sb.AppendLine("        fastcgi_param  SCRIPT_FILENAME $document_root$fastcgi_script_name;");
                    sb.AppendLine("        include        fastcgi_params;");
                    sb.AppendLine("    }");
                }
                sb.AppendLine("}");
            }

            string? backupPath = null;
            if (File.Exists(confFile))
            {
                backupPath = FileBackupHelper.CreateBackup(confFile, _logger);
            }

            await File.WriteAllTextAsync(confFile, sb.ToString());

            // Validate syntax before applying (Fix.md Section 5)
            var (isValid, errorOutput) = await ValidateConfigurationAsync();
            if (!isValid)
            {
                _logger.LogError("Nginx", $"Server block validation failed for '{project.Domain}': {errorOutput}. Rolling back configuration.");
                if (backupPath != null && File.Exists(backupPath))
                {
                    File.Copy(backupPath, confFile, overwrite: true);
                }
                else if (File.Exists(confFile))
                {
                    File.Delete(confFile);
                }
                return false;
            }

            _logger.LogInfo("Nginx", $"Server block validated and generated for '{project.Domain}' at '{confFile}'.");
            await ReloadConfigurationAsync();
            return true;
        }
        catch (Exception ex)
        {
            _logger.LogError("Nginx", $"Failed to generate server block for '{project.Domain}'", ex);
            return false;
        }
    }

    public async Task<bool> ReloadConfigurationAsync()
    {
        var info = await _detector.DetectNginxAsync();
        if (info == null || !info.IsInstalled || !File.Exists(info.ExecutablePath))
        {
            return false;
        }

        var (isValid, _) = await ValidateConfigurationAsync();
        if (!isValid)
        {
            return false;
        }

        try
        {
            var nginxProcs = System.Diagnostics.Process.GetProcessesByName("nginx");
            if (nginxProcs.Length == 0)
            {
                return true;
            }

            var confPath = Path.Combine(_configService.Config.Paths.EtcPath, "nginx", "nginx.conf");
            var confArg = File.Exists(confPath) ? $" -c \"{confPath.Replace('\\', '/')}\"" : "";
            var dirArg = info.DirectoryPath.Replace('\\', '/');
            var result = await _processManager.ExecuteAsync(info.ExecutablePath, $"-p \"{dirArg}\"{confArg} -s reload", workingDirectory: info.DirectoryPath);
            if (result.Success)
            {
                _logger.LogInfo("Nginx", "Configuration reloaded successfully via signal.");
                return true;
            }

            _logger.LogWarning("Nginx", $"Nginx reload signal returned ({result.ExitCode}): {result.StandardError}.");
            return true;
        }
        catch (Exception ex)
        {
            _logger.LogWarning("Nginx", $"Failed to reload Nginx configuration: {ex.Message}");
            return false;
        }
    }

    public async Task<bool> UpdatePortConfigurationAsync(int port)
    {
        var info = await _detector.DetectNginxAsync();
        if (info == null || !info.IsInstalled || !File.Exists(info.ExecutablePath))
        {
            return false;
        }

        try
        {
            var confCandidates = new List<string>
            {
                Path.Combine(info.DirectoryPath, "conf", "nginx.conf"),
                Path.Combine(_configService.Config.Paths.EtcPath, "nginx", "nginx.conf")
            };

            bool anyUpdated = false;
            foreach (var confFile in confCandidates.Distinct().Where(File.Exists))
            {
                var content = await File.ReadAllTextAsync(confFile);
                var listenRegex = new System.Text.RegularExpressions.Regex(@"(listen\s+)\d+(\s+default_server;)?");
                if (!content.Contains("location /phpmyadmin"))
                {
                    var pmaDir = Path.Combine(_configService.Config.Paths.BinPath, "phpmyadmin").Replace('\\', '/');
                    var pmaBlock = $@"
        location /phpmyadmin {{
            alias ""{pmaDir}"";
            index index.php index.html index.htm;

            location ~ \.php$ {{
                fastcgi_pass   127.0.0.1:9000;
                fastcgi_index  index.php;
                fastcgi_param  SCRIPT_FILENAME $request_filename;
                include        fastcgi_params;
            }}
        }}";
                    var serverRegex = new System.Text.RegularExpressions.Regex(@"(server\s*\{[^}]*?root\s+[^;]+;\s*index\s+[^;]+;)");
                    if (serverRegex.IsMatch(content))
                    {
                        content = serverRegex.Replace(content, m => m.Value + "\r\n" + pmaBlock);
                        anyUpdated = true;
                    }
                }

                if (listenRegex.IsMatch(content))
                {
                    content = listenRegex.Replace(content, m => $"{m.Groups[1].Value}{port}{m.Groups[2].Value}");
                    await File.WriteAllTextAsync(confFile, content);
                    _logger.LogInfo("Nginx", $"Updated Nginx port to {port} in {confFile}.");
                    anyUpdated = true;
                }
            }
            return anyUpdated;
        }
        catch (Exception ex)
        {
            _logger.LogError("Nginx", $"Failed to update Nginx port configuration: {ex.Message}", ex);
            return false;
        }
    }
}
