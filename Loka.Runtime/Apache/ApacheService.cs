using System.Text;
using Loka.Core.Enums;
using Loka.Core.Interfaces;
using Loka.Core.Models;
using Loka.Infrastructure.FileSystem;

namespace Loka.Runtime.Apache;

public class ApacheService : IApacheService
{
    private readonly IConfigurationService _configService;
    private readonly IRuntimeDetector _detector;
    private readonly IProcessManager _processManager;
    private readonly ILogService _logger;

    public ApacheService(
        IConfigurationService configService,
        IRuntimeDetector detector,
        IProcessManager processManager,
        ILogService logger)
    {
        _configService = configService;
        _detector = detector;
        _processManager = processManager;
        _logger = logger;
    }

    public async Task<(bool IsValid, string Output)> ValidateConfigurationAsync()
    {
        var info = await _detector.DetectApacheAsync();
        if (info == null || !info.IsInstalled || !File.Exists(info.ExecutablePath))
        {
            return (false, "Apache executable not found.");
        }

        try
        {
            var apacheDir = Directory.GetParent(info.DirectoryPath)?.FullName ?? info.DirectoryPath;
            var vhostConfigDir = Path.Combine(_configService.Config.Paths.ConfigPath, "apache", "sites-enabled");
            if (!Directory.Exists(vhostConfigDir)) Directory.CreateDirectory(vhostConfigDir);
            var vhostEtcDir = Path.Combine(_configService.Config.Paths.EtcPath, "apache", "sites-enabled");
            if (!Directory.Exists(vhostEtcDir)) Directory.CreateDirectory(vhostEtcDir);
            var logsDir = Path.Combine(_configService.Config.Paths.LogsPath, "apache");
            if (!Directory.Exists(logsDir)) Directory.CreateDirectory(logsDir);

            var result = await _processManager.ExecuteAsync(
                info.ExecutablePath,
                $"-d \"{apacheDir.Replace('\\', '/')}\" -t",
                workingDirectory: apacheDir);

            var output = (result.StandardOutput + " " + result.StandardError).Trim();
            bool isValid = result.Success && output.Contains("Syntax OK", StringComparison.OrdinalIgnoreCase);

            if (isValid)
            {
                _logger.LogInfo("Apache", "Configuration syntax is OK.");
            }
            else
            {
                _logger.LogError("Apache", $"Configuration validation failed: {output}");
            }

            return (isValid, output);
        }
        catch (Exception ex)
        {
            _logger.LogError("Apache", "Exception during configuration validation", ex);
            return (false, ex.Message);
        }
    }

    public async Task<bool> GenerateVHostConfigAsync(ProjectInfo project)
    {
        try
        {
            var vhostDir = Path.Combine(_configService.Config.Paths.ConfigPath, "apache", "sites-enabled");
            if (!Directory.Exists(vhostDir))
            {
                Directory.CreateDirectory(vhostDir);
            }

            var docRoot = string.IsNullOrEmpty(project.DocumentRoot) ? project.Path : project.DocumentRoot;
            docRoot = docRoot.Replace('\\', '/');

            var vhostFile = Path.Combine(vhostDir, $"{project.Domain}.conf");
            var sb = new StringBuilder();

            bool isStaticOnly = project.Framework == ProjectFramework.StaticHtml ||
                               (project.Framework == ProjectFramework.React && !File.Exists(Path.Combine(docRoot, "index.php"))) ||
                               (project.Framework == ProjectFramework.Vue && !File.Exists(Path.Combine(docRoot, "index.php"))) ||
                               (project.Framework == ProjectFramework.Vite && !File.Exists(Path.Combine(docRoot, "index.php")));

            var defaultIndex = isStaticOnly ? "index.html index.htm default.html" : "index.php index.html index.htm default.php default.html";
            var rewriteRule = isStaticOnly ? "RewriteRule ^ index.html [L]" : "RewriteRule ^ index.php [QSA,L]";

            var sslCertDir = Path.Combine(_configService.Config.Paths.ConfigPath, "ssl").Replace('\\', '/');
            var certPath = Path.Combine(_configService.Config.Paths.ConfigPath, "ssl", $"{project.Domain}.crt");
            var keyPath = Path.Combine(_configService.Config.Paths.ConfigPath, "ssl", $"{project.Domain}.key");
            bool hasSsl = project.HasSsl || (File.Exists(certPath) && File.Exists(keyPath));

            sb.AppendLine($"# VirtualHost for {project.Domain} generated by Loka ({project.FrameworkName})");
            sb.AppendLine($"<VirtualHost *:{_configService.Config.Services.ApachePort}>");
            sb.AppendLine($"    DocumentRoot \"{docRoot}\"");
            sb.AppendLine($"    ServerName {project.Domain}");
            sb.AppendLine($"    ServerAlias www.{project.Domain}");
            sb.AppendLine($"    <Directory \"{docRoot}\">");
            sb.AppendLine("        Options Indexes FollowSymLinks MultiViews");
            sb.AppendLine("        AllowOverride All");
            sb.AppendLine("        Require all granted");
            sb.AppendLine($"        DirectoryIndex {defaultIndex}");
            sb.AppendLine("        <IfModule mod_rewrite.c>");
            sb.AppendLine("            RewriteEngine On");
            sb.AppendLine("            RewriteCond %{REQUEST_FILENAME} !-f");
            sb.AppendLine("            RewriteCond %{REQUEST_FILENAME} !-d");
            sb.AppendLine($"            {rewriteRule}");
            sb.AppendLine("        </IfModule>");
            sb.AppendLine("    </Directory>");
            if (!isStaticOnly)
            {
                sb.AppendLine("    <IfModule mod_proxy_fcgi.c>");
                sb.AppendLine("        ProxyFCGISetEnvIf \"true\" SCRIPT_FILENAME \"%{reqenv:DOCUMENT_ROOT}%{reqenv:SCRIPT_NAME}\"");
                sb.AppendLine("        <FilesMatch \\.php$>");
                sb.AppendLine("            SetHandler \"proxy:fcgi://127.0.0.1:9000/\"");
                sb.AppendLine("        </FilesMatch>");
                sb.AppendLine("    </IfModule>");
            }
            sb.AppendLine($"    ErrorLog \"{_configService.Config.Paths.LogsPath.Replace('\\', '/')}/apache_{project.Domain}_error.log\"");
            sb.AppendLine($"    CustomLog \"{_configService.Config.Paths.LogsPath.Replace('\\', '/')}/apache_{project.Domain}_access.log\" common");
            sb.AppendLine("</VirtualHost>");

            if (hasSsl)
            {
                sb.AppendLine();
                sb.AppendLine($"<VirtualHost *:{_configService.Config.Services.ApacheSslPort}>");
                sb.AppendLine($"    DocumentRoot \"{docRoot}\"");
                sb.AppendLine($"    ServerName {project.Domain}");
                sb.AppendLine($"    ServerAlias www.{project.Domain}");
                sb.AppendLine("    SSLEngine on");
                sb.AppendLine($"    SSLCertificateFile \"{sslCertDir}/{project.Domain}.crt\"");
                sb.AppendLine($"    SSLCertificateKeyFile \"{sslCertDir}/{project.Domain}.key\"");
                sb.AppendLine($"    <Directory \"{docRoot}\">");
                sb.AppendLine("        Options Indexes FollowSymLinks MultiViews");
                sb.AppendLine("        AllowOverride All");
                sb.AppendLine("        Require all granted");
                sb.AppendLine($"        DirectoryIndex {defaultIndex}");
                sb.AppendLine("        <IfModule mod_rewrite.c>");
                sb.AppendLine("            RewriteEngine On");
                sb.AppendLine("            RewriteCond %{REQUEST_FILENAME} !-f");
                sb.AppendLine("            RewriteCond %{REQUEST_FILENAME} !-d");
                sb.AppendLine($"            {rewriteRule}");
                sb.AppendLine("        </IfModule>");
                sb.AppendLine("    </Directory>");
                if (!isStaticOnly)
                {
                    sb.AppendLine("    <IfModule mod_proxy_fcgi.c>");
                    sb.AppendLine("        ProxyFCGISetEnvIf \"true\" SCRIPT_FILENAME \"%{reqenv:DOCUMENT_ROOT}%{reqenv:SCRIPT_NAME}\"");
                    sb.AppendLine("        <FilesMatch \\.php$>");
                    sb.AppendLine("            SetHandler \"proxy:fcgi://127.0.0.1:9000/\"");
                    sb.AppendLine("        </FilesMatch>");
                    sb.AppendLine("    </IfModule>");
                }
                sb.AppendLine($"    ErrorLog \"{_configService.Config.Paths.LogsPath.Replace('\\', '/')}/apache_{project.Domain}_ssl_error.log\"");
                sb.AppendLine($"    CustomLog \"{_configService.Config.Paths.LogsPath.Replace('\\', '/')}/apache_{project.Domain}_ssl_access.log\" common");
                sb.AppendLine("</VirtualHost>");
            }

            string? backupPath = null;
            if (File.Exists(vhostFile))
            {
                backupPath = FileBackupHelper.CreateBackup(vhostFile, _logger);
            }

            await File.WriteAllTextAsync(vhostFile, sb.ToString());

            // Validate syntax before applying (Fix.md Section 5)
            var (isValid, errorOutput) = await ValidateConfigurationAsync();
            if (!isValid)
            {
                _logger.LogError("Apache", $"Virtual host validation failed for '{project.Domain}': {errorOutput}. Rolling back configuration.");
                if (backupPath != null && File.Exists(backupPath))
                {
                    File.Copy(backupPath, vhostFile, overwrite: true);
                }
                else if (File.Exists(vhostFile))
                {
                    File.Delete(vhostFile);
                }
                return false;
            }

            _logger.LogInfo("Apache", $"Virtual host configuration validated and generated for '{project.Domain}' at '{vhostFile}'.");
            await ReloadConfigurationAsync();
            return true;
        }
        catch (Exception ex)
        {
            _logger.LogError("Apache", $"Failed to generate virtual host for '{project.Domain}'", ex);
            return false;
        }
    }

    public async Task<bool> ReloadConfigurationAsync()
    {
        var info = await _detector.DetectApacheAsync();
        if (info == null || !info.IsInstalled || !File.Exists(info.ExecutablePath))
        {
            return false;
        }

        var (isValid, _) = await ValidateConfigurationAsync();
        if (!isValid) return false;

        try
        {
            var httpdProcs = System.Diagnostics.Process.GetProcessesByName("httpd");
            if (httpdProcs.Length == 0) return true;

            var apacheDir = Directory.GetParent(info.DirectoryPath)?.FullName ?? info.DirectoryPath;
            var result = await _processManager.ExecuteAsync(
                info.ExecutablePath,
                $"-d \"{apacheDir.Replace('\\', '/')}\" -k restart",
                workingDirectory: apacheDir);
            return result.Success;
        }
        catch (Exception ex)
        {
            _logger.LogWarning("Apache", $"Failed to reload Apache: {ex.Message}");
            return false;
        }
    }

    public async Task<bool> UpdatePortConfigurationAsync(int port, int sslPort)
    {
        var info = await _detector.DetectApacheAsync();
        if (info == null || !info.IsInstalled || !File.Exists(info.ExecutablePath))
        {
            return false;
        }

        try
        {
            var confCandidates = new List<string>
            {
                Path.GetFullPath(Path.Combine(info.DirectoryPath, "..", "conf", "httpd.conf")),
                Path.Combine(info.DirectoryPath, "httpd.conf"),
                Path.Combine(_configService.Config.Paths.EtcPath, "apache", "httpd.conf"),
                Path.Combine(_configService.Config.Paths.ConfigPath, "apache", "httpd.conf")
            };

            bool anyUpdated = false;
            foreach (var confPath in confCandidates.Distinct().Where(File.Exists))
            {
                var content = await File.ReadAllTextAsync(confPath);

                // Strip old Listen directives
                content = System.Text.RegularExpressions.Regex.Replace(content, @"(?m)^\s*Listen\s+.*$\r?\n?", "");

                // Insert configured Listen ports
                if (System.Text.RegularExpressions.Regex.IsMatch(content, @"(?m)^\s*#\s*Listen\s+12\.34\.56\.78:80.*$"))
                {
                    content = System.Text.RegularExpressions.Regex.Replace(
                        content,
                        @"(?m)^\s*#\s*Listen\s+12\.34\.56\.78:80.*$",
                        $"#Listen 12.34.56.78:80\r\nListen {port}\r\nListen {sslPort}");
                }
                else
                {
                    content = $"Listen {port}\r\nListen {sslPort}\r\n" + content;
                }

                // Update ServerName
                content = System.Text.RegularExpressions.Regex.Replace(
                    content,
                    @"(?m)^\s*#?\s*ServerName\s+[^:\r\n]+(:\d+)?",
                    $"ServerName localhost:{port}");

                var projectsDir = _configService.Config.Paths.ProjectsPath.Replace('\\', '/');
                var pmaDir = Path.Combine(_configService.Config.Paths.BinPath, "phpmyadmin").Replace('\\', '/');
                var logsDir = _configService.Config.Paths.LogsPath.Replace('\\', '/');

                var defaultVhost = $@"# Loka Default VirtualHost (Catch-all for localhost & 127.0.0.1)
<VirtualHost *:{port}>
    ServerName localhost
    ServerAlias 127.0.0.1
    DocumentRoot ""{projectsDir}""

    <Directory ""{projectsDir}"">
        Options Indexes FollowSymLinks MultiViews
        AllowOverride All
        Require all granted
        DirectoryIndex index.php index.html index.htm
        <IfModule mod_rewrite.c>
            RewriteEngine On
        </IfModule>
        <IfModule mod_proxy_fcgi.c>
            ProxyFCGISetEnvIf ""true"" SCRIPT_FILENAME ""%{{reqenv:DOCUMENT_ROOT}}%{{reqenv:SCRIPT_NAME}}""
            <FilesMatch \.php$>
                SetHandler ""proxy:fcgi://127.0.0.1:9000/""
            </FilesMatch>
        </IfModule>
    </Directory>

    Alias /phpmyadmin ""{pmaDir}""
    <Directory ""{pmaDir}"">
        Options Indexes FollowSymLinks MultiViews
        AllowOverride All
        Require all granted
        DirectoryIndex index.php index.html index.htm
        <IfModule mod_proxy_fcgi.c>
            ProxyFCGISetEnvIf ""reqenv('SCRIPT_NAME') =~ m#^/phpmyadmin/(.*)$#"" SCRIPT_FILENAME ""{pmaDir}/$1""
            <FilesMatch \.php$>
                SetHandler ""proxy:fcgi://127.0.0.1:9000/""
            </FilesMatch>
        </IfModule>
    </Directory>

    ErrorLog ""{logsDir}/apache_default_error.log""
    CustomLog ""{logsDir}/apache_default_access.log"" common
</VirtualHost>";

                if (System.Text.RegularExpressions.Regex.IsMatch(content, @"(?s)# Loka Default VirtualHost.*?</VirtualHost>"))
                {
                    content = System.Text.RegularExpressions.Regex.Replace(
                        content,
                        @"(?s)# Loka Default VirtualHost.*?</VirtualHost>",
                        defaultVhost);
                }
                else if (content.Contains("# Loka Projects Sites"))
                {
                    content = content.Replace("# Loka Projects Sites", defaultVhost + "\r\n\r\n# Loka Projects Sites");
                }
                else
                {
                    content += "\r\n\r\n" + defaultVhost + "\r\n";
                }

                // Ensure dynamic sites-enabled paths
                var dynamicCfgApache = $"{_configService.Config.Paths.ConfigPath.Replace('\\', '/')}/apache/sites-enabled/*.conf";
                var dynamicEtcApache = $"{_configService.Config.Paths.EtcPath.Replace('\\', '/')}/apache/sites-enabled/*.conf";
                if (!content.Contains("Loka Projects Sites"))
                {
                    content += $"\r\n# Loka Projects Sites\r\nIncludeOptional \"{dynamicCfgApache}\"\r\nIncludeOptional \"{dynamicEtcApache}\"\r\n";
                }
                else
                {
                    content = System.Text.RegularExpressions.Regex.Replace(content, @"IncludeOptional "".*?/config/apache/sites-enabled/\*\.conf""", $"IncludeOptional \"{dynamicCfgApache}\"");
                    content = System.Text.RegularExpressions.Regex.Replace(content, @"IncludeOptional "".*?/etc/apache/sites-enabled/\*\.conf""", $"IncludeOptional \"{dynamicEtcApache}\"");
                }

                await File.WriteAllTextAsync(confPath, content);
                _logger.LogInfo("Apache", $"Updated Apache port to {port}/{sslPort} in {confPath}.");
                anyUpdated = true;
            }

            return anyUpdated;
        }
        catch (Exception ex)
        {
            _logger.LogError("Apache", $"Failed to update Apache port configuration: {ex.Message}", ex);
            return false;
        }
    }
}
